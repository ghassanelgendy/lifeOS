const DAILY_HADITH_STORAGE_KEY = 'lifeos_daily_hadith_assignments_v2';

/**
 * Gets a distinct date string 'YYYY-MM-DD' representing local calendar day
 */
export function getLocalDateString(date: Date = new Date()): string {
  const year = date.getFullYear();
  const month = String(date.getMonth() + 1).padStart(2, '0');
  const day = String(date.getDate()).padStart(2, '0');
  return `${year}-${month}-${day}`;
}

/**
 * Calculates days elapsed since base epoch (2024-01-01) in local time
 */
function getDaysSinceEpoch(dateStr: string): number {
  const [y, m, d] = dateStr.split('-').map(Number);
  const epoch = new Date(2024, 0, 1).getTime();
  const current = new Date(y, m - 1, d).getTime();
  return Math.max(0, Math.floor((current - epoch) / (1000 * 60 * 60 * 24)));
}

/**
 * Full-period coprime pseudo-random permutation index.
 * Guarantees that across all 367 entries in SHORT_HADITHS, every consecutive day index
 * generates a distinct, non-repeating Hadith in a cycle of length SHORT_HADITHS.length.
 */
function getPermutationIndex(dayIndex: number, total: number): number {
  // Coprime multiplier with total length to create a full permutation cycle with zero collisions across total days
  const coprime = 137;
  const offset = 42;
  return ((dayIndex * coprime + offset) % total + total) % total;
}

/**
 * Returns the daily hadith for a given date (defaults to today).
 * Ensures that:
 * 1. The Hadith is different every single day.
 * 2. It never repeats across days:
 *    - Uses a deterministic full-period permutation across all 367 authentic hadiths.
 *    - Persists assignments in localStorage to guarantee unique assignment history per day.
 */
export function getDailyHadith(dateStr?: string): ShortHadith {
  const targetDate = dateStr || getLocalDateString();
  const total = SHORT_HADITHS.length;

  if (typeof window !== 'undefined' && window.localStorage) {
    try {
      const rawMap = localStorage.getItem(DAILY_HADITH_STORAGE_KEY);
      const assignments: Record<string, string> = rawMap ? JSON.parse(rawMap) : {};

      // If already assigned for this specific date, return it
      if (assignments[targetDate]) {
        const existing = SHORT_HADITHS.find((h) => h.id === assignments[targetDate]);
        if (existing) return existing;
      }

      // Collect all already assigned hadith IDs in history
      const assignedIds = new Set(Object.values(assignments));

      // If all hadiths have been seen, we start a fresh cycle
      if (assignedIds.size >= total) {
        assignedIds.clear();
      }

      // Calculate candidate index from epoch progression
      const dayIndex = getDaysSinceEpoch(targetDate);
      let permIndex = getPermutationIndex(dayIndex, total);

      // Ensure no collision with previously assigned hadiths in the current cycle
      let candidate = SHORT_HADITHS[permIndex];
      let attempts = 0;
      while (assignedIds.has(candidate.id) && attempts < total) {
        permIndex = (permIndex + 1) % total;
        candidate = SHORT_HADITHS[permIndex];
        attempts++;
      }

      // Store assignment
      assignments[targetDate] = candidate.id;
      localStorage.setItem(DAILY_HADITH_STORAGE_KEY, JSON.stringify(assignments));

      return candidate;
    } catch (e) {
      console.warn('Hadith localStorage error, falling back to deterministic calculation', e);
    }
  }

  // Fallback: pure mathematical non-repeating permutation based on calendar day
  const dayIndex = getDaysSinceEpoch(targetDate);
  const permIndex = getPermutationIndex(dayIndex, total);
  return SHORT_HADITHS[permIndex] || SHORT_HADITHS[0];
}

/**
 * Gets a random Hadith, avoiding recently viewed ones in the session
 */
export function getRandomHadith(currentIndex?: number, excludeIds?: string[]): { hadith: ShortHadith; index: number } {
  const total = SHORT_HADITHS.length;
  if (total <= 1) return { hadith: SHORT_HADITHS[0], index: 0 };

  const excludeSet = new Set<string>(excludeIds || []);
  if (currentIndex !== undefined && SHORT_HADITHS[currentIndex]) {
    excludeSet.add(SHORT_HADITHS[currentIndex].id);
  }

  const candidates = SHORT_HADITHS.map((h, i) => ({ hadith: h, index: i })).filter(
    (item) => !excludeSet.has(item.hadith.id)
  );

  const pool = candidates.length > 0 ? candidates : SHORT_HADITHS.map((h, i) => ({ hadith: h, index: i }));
  const randomPick = pool[Math.floor(Math.random() * pool.length)];

  return randomPick;
}
